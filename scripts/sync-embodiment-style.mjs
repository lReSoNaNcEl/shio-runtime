import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { isDeepStrictEqual } from 'node:util'

// Desktop-only delivery style contract. The emotion contract and the generated
// Fish/API manifests are read, never written, by this script.
const require = createRequire(new URL('../apps/desktop/package.json', import.meta.url))
const read = (relative) => JSON.parse(readFileSync(new URL(`../${relative}`, import.meta.url), 'utf8'))
const emotions = read('contracts/emotions.v3.json').emotions.map((entry) => entry.id)
const contract = read('contracts/embodiment-style.v1.json')
const AXES = ['openness', 'height', 'tempo', 'sharpness', 'asymmetry', 'lean']
const MOOD = ['valence', 'arousal', 'playfulness', 'curiosity', 'frustration']
const fail = (message) => {
  throw new Error(`Invalid embodiment style contract: ${message}`)
}
const sameKeys = (value, keys) =>
  value && typeof value === 'object' && isDeepStrictEqual(Object.keys(value).sort(), [...keys].sort())
const finite = (value) => typeof value === 'number' && Number.isFinite(value)

if (contract.schemaVersion !== 1) fail('schemaVersion')
if (!sameKeys(contract.axes, AXES)) fail('axes')
for (const axis of AXES) {
  const [low, high] = contract.axes[axis]
  if (!finite(low) || !finite(high) || low >= high || low < -1 || high > 1) fail(`range ${axis}`)
}
const validStyle = (style, name) => {
  if (!sameKeys(style, AXES)) fail(`${name} axes`)
  for (const axis of AXES) {
    const [low, high] = contract.axes[axis]
    if (!finite(style[axis]) || style[axis] < low || style[axis] > high) fail(`${name}.${axis}`)
  }
}
validStyle(contract.default, 'default')
if (!sameKeys(contract.intensity, ['subtle', 'normal', 'strong'])) fail('intensity')
for (const value of Object.values(contract.intensity)) if (!finite(value) || value <= 0 || value > 1.5) fail('intensity value')
for (const id of Object.keys(contract.emotions)) if (!emotions.includes(id)) fail(`unknown emotion ${id}`)
for (const id of emotions) if (contract.emotions[id]) validStyle(contract.emotions[id], id)
const mood = contract.mood
if (!sameKeys(mood, ['maxShift', 'centers', 'coefficients'])) fail('mood')
if (!finite(mood.maxShift) || mood.maxShift <= 0 || mood.maxShift > 0.15) fail('mood.maxShift')
if (!sameKeys(mood.centers, MOOD)) fail('mood.centers')
for (const [axis, coefficients] of Object.entries(mood.coefficients)) {
  if (!AXES.includes(axis)) fail(`mood axis ${axis}`)
  for (const [dimension, value] of Object.entries(coefficients))
    if (!MOOD.includes(dimension) || !finite(value) || Math.abs(value) > 0.5) fail(`mood.${axis}.${dimension}`)
}

const desktop = fileURLToPath(new URL('../apps/desktop', import.meta.url))
const tsTarget = new URL('../apps/desktop/src/shared/embodiment/embodimentStyle.generated.ts', import.meta.url)
const pyTarget = new URL('../apps/desktop/motionbricks/embodiment_style.json', import.meta.url)
const resolved = { ...contract, emotions: Object.fromEntries(emotions.map((id) => [id, contract.emotions[id] ?? contract.default])) }
delete resolved.description
const source = `// Generated by scripts/sync-embodiment-style.mjs; edit contracts/embodiment-style.v1.json.\nexport const EMBODIMENT_STYLE_CONTRACT = ${JSON.stringify(resolved)} as const\n`
const biome = require.resolve('@biomejs/biome/bin/biome')
const formatted = spawnSync(process.execPath, [biome, 'format', '--stdin-file-path', fileURLToPath(tsTarget)], {
  cwd: desktop, input: source, encoding: 'utf8', windowsHide: true, maxBuffer: 4 * 1024 * 1024,
})
if (formatted.error || formatted.status !== 0) throw new Error('Embodiment style formatting failed', { cause: formatted.error ?? formatted.stderr })
const python = { schemaVersion: contract.schemaVersion, axes: contract.axes, default: contract.default }
if (process.argv.includes('--check')) {
  const stale = (path) => {
    throw new Error(`Stale generated embodiment style: ${fileURLToPath(path)}. Run npm run embodiment:sync`)
  }
  let typescript = ''
  let worker = null
  try {
    typescript = readFileSync(tsTarget, 'utf8')
    worker = JSON.parse(readFileSync(pyTarget, 'utf8'))
  } catch {
    stale(typescript ? pyTarget : tsTarget)
  }
  if (typescript !== formatted.stdout) stale(tsTarget)
  if (!isDeepStrictEqual(worker, python)) stale(pyTarget)
} else {
  writeFileSync(tsTarget, formatted.stdout)
  writeFileSync(pyTarget, `${JSON.stringify(python, null, 2)}\n`)
}
console.log(`Validated embodiment style for ${emotions.length} emotions`)
