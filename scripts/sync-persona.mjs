import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

// Bundled Shio persona contract -> generated Main-only TypeScript. The renderer
// never edits or reads the persona; it is part of the Character request only.
const require = createRequire(new URL('../apps/desktop/package.json', import.meta.url))
const contract = JSON.parse(readFileSync(new URL('../contracts/persona.v1.json', import.meta.url), 'utf8'))
const PERSONA_BUDGET = 5_500
const fail = (message) => {
  throw new Error(`Invalid persona contract: ${message}`)
}
if (contract.schemaVersion !== 1) fail('schemaVersion')
if (!Array.isArray(contract.sections) || contract.sections.length === 0) fail('sections')
const ids = new Set()
let characters = 0
for (const section of contract.sections) {
  if (!section || typeof section.id !== 'string' || !/^[a-zA-Z]{1,40}$/u.test(section.id)) fail('section id')
  if (ids.has(section.id)) fail(`duplicate section ${section.id}`)
  ids.add(section.id)
  if (typeof section.title !== 'string' || !section.title.trim() || section.title.length > 60) fail(`${section.id}.title`)
  if (!Array.isArray(section.lines) || section.lines.length === 0) fail(`${section.id}.lines`)
  for (const line of section.lines)
    if (typeof line !== 'string' || !line.trim() || line.length > 400 || /[\r\n]/u.test(line)) fail(`${section.id} line`)
  characters += section.title.length + section.lines.reduce((sum, line) => sum + line.length + 1, 4)
}
if (characters > PERSONA_BUDGET) fail(`persona exceeds the ${PERSONA_BUDGET}-character Composer budget`)

const sections = Object.fromEntries(contract.sections.map(({ id, title, lines }) => [id, [title, ...lines]]))
const source = `// Generated by scripts/sync-persona.mjs; edit contracts/persona.v1.json.\nexport const PERSONA_PROMPT_SECTIONS = ${JSON.stringify(sections)} as const\n`
const target = new URL('../apps/desktop/src/main/character/prompting/persona.generated.ts', import.meta.url)
const biome = require.resolve('@biomejs/biome/bin/biome')
const formatted = spawnSync(process.execPath, [biome, 'format', '--stdin-file-path', fileURLToPath(target)], {
  cwd: fileURLToPath(new URL('../apps/desktop', import.meta.url)),
  input: source,
  encoding: 'utf8',
  windowsHide: true,
  maxBuffer: 4 * 1024 * 1024,
})
if (formatted.error || formatted.status !== 0) throw new Error('Persona formatting failed', { cause: formatted.error ?? formatted.stderr })
if (process.argv.includes('--check')) {
  let actual = ''
  try {
    actual = readFileSync(target, 'utf8')
  } catch {}
  if (actual !== formatted.stdout) throw new Error('Stale generated persona. Run npm run persona:sync')
} else writeFileSync(target, formatted.stdout)
console.log(`Validated ${contract.sections.length} persona sections (${characters} characters)`)
