import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { isDeepStrictEqual } from 'node:util'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const contract = JSON.parse(readFileSync(path.join(root, 'contracts/emotions.v3.json'), 'utf8'))
const ids = contract.emotions.map((entry) => entry.id)
if (contract.intensity?.values.join('|') !== 'subtle|normal|strong' || contract.delivery?.styleMaxCharacters !== 120 || contract.grammar?.version !== 1) throw new Error('Invalid canonical delivery grammar')
if (contract.schemaVersion !== 3 || new Set(ids).size !== ids.length || !ids.includes(contract.defaultEmotion)) {
  throw new Error('Invalid canonical emotion contract')
}
for (const entry of contract.emotions) {
  if (entry.avatar.modelVersion !== undefined || !entry.avatar.bodyIntent || !Array.isArray(entry.speech.fishTags)) {
    throw new Error(`Invalid VRM/Fish emotion mapping: ${entry.id}`)
  }
}
const json = `${JSON.stringify(contract, null, 2)}\n`
const generated = new Map([
  ['apps/api/emotion_manifest.json', json],
  ['apps/desktop/emotion_manifest.json', json.replaceAll('\n', '\r\n')],
  ['apps/desktop/src/shared/speech/emotions.generated.ts', `// Generated by scripts/sync-emotions.mjs.\r\nexport const SPEECH_EMOTIONS = [\r\n${ids.map((id) => `  '${id}',`).join('\r\n')}\r\n] as const\r\nexport const EMOTION_INTENSITIES = [${contract.intensity.values.map((value) => `'${value}'`).join(', ')}] as const\r\n`],
])
for (const [relative, content] of generated) {
  const target = path.join(root, relative)
  if (process.argv.includes('--check')) {
    const actual = readFileSync(target, 'utf8')
    const matches = relative.endsWith('.json') ? isDeepStrictEqual(JSON.parse(actual), JSON.parse(content)) : actual.replace(/\s+/g, '') === content.replace(/\s+/g, '')
    if (!matches) throw new Error(`Stale generated emotion contract: ${relative}`)
  } else writeFileSync(target, content)
}
console.log(`Synchronized ${ids.length} VRM/Fish emotion cues`)
