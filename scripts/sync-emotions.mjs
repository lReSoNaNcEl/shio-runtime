import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const contract = JSON.parse(await fs.readFile(path.join(root, 'contracts/emotions.v2.json'), 'utf8'))
const serialized = `${JSON.stringify(contract, null, 2)}\n`
for (const destination of ['apps/api/emotion_manifest.json', 'apps/desktop/emotion_manifest.json', 'apps/shio-2d/emotion_manifest.json']) {
  await fs.writeFile(path.join(root, destination), serialized)
}
const keys = contract.emotions.map((entry) => entry.id)
await fs.writeFile(path.join(root, 'apps/desktop/src/shared/speech/emotions.generated.ts'),
  `// Generated by scripts/sync-emotions.mjs.\nexport const SPEECH_EMOTIONS = ${JSON.stringify(keys, null, 2)} as const\n`)
console.log(`Synchronized ${keys.length} semantic expression cues`)
