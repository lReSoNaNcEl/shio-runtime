import { spawnSync } from 'node:child_process'
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { isDeepStrictEqual } from 'node:util'

const require = createRequire(new URL('../apps/desktop/package.json', import.meta.url))
const { buildSync } = require('esbuild')
const compiled = buildSync({
  entryPoints: [fileURLToPath(new URL('../apps/desktop/src/shared/motion/catalogSchema.ts', import.meta.url))],
  bundle: true, platform: 'node', format: 'esm', write: false,
}).outputFiles[0].text
const { motionCatalogSchema } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`)
const source = new URL('../contracts/motion.v1.json', import.meta.url)
const target = new URL('../apps/desktop/motion/motion-profiles.json', import.meta.url)
const types = new URL('../apps/desktop/src/shared/motion/catalog.generated.ts', import.meta.url)
const raw = readFileSync(source, 'utf8')
const catalog = motionCatalogSchema.parse(JSON.parse(raw))
const generated = (`// Generated by scripts/sync-motion.mjs; edit contracts/motion.v1.json.\nexport const MOTION_PROFILE_IDS = [\n${catalog.profiles.map((p) => `  '${p.id}',`).join('\n')}\n] as const\nexport type MotionProfileId = (typeof MOTION_PROFILE_IDS)[number]\n`).replaceAll('\n', '\r\n')
if (process.argv.includes('--check')) {
  if (!isDeepStrictEqual(JSON.parse(readFileSync(target, 'utf8')), catalog) || readFileSync(types, 'utf8') !== generated) throw new Error('Run npm run motion:sync')
} else {
  const biome = require.resolve('@biomejs/biome/bin/biome')
  const formatted = spawnSync(process.execPath, [biome, 'format', '--stdin-file-path', fileURLToPath(target)], {
    cwd: fileURLToPath(new URL('../apps/desktop', import.meta.url)), input: raw, encoding: 'utf8', windowsHide: true,
    maxBuffer: 4 * 1024 * 1024,
  })
  if (formatted.error || formatted.status !== 0) throw new Error('Motion catalog formatting failed', { cause: formatted.error ?? formatted.stderr })
  writeFileSync(target, formatted.stdout)
  writeFileSync(types, generated)
}
console.log(`Validated ${catalog.profiles.length} motion profiles (${catalog.catalogRevision}): ${fileURLToPath(target)}`)
